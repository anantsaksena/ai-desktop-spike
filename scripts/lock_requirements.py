#!/usr/bin/env python3
"""Generate requirements.lock (pinned + hashed) from requirements.txt.

Every `name==version` line gets one --hash per file PyPI publishes for that
release (all wheels + sdist), taken from PyPI's JSON API, i.e. the digests
recorded at upload time, NOT hashes of whatever we happen to download. The
build then installs with:

    pip install --require-hashes --only-binary :all: -r requirements.lock

--require-hashes: pip refuses any file whose hash isn't listed, and any
  dependency that isn't pinned in the lock.
--only-binary :all: no sdist builds. pip can't hash-check the build
  dependencies an sdist build would fetch, so we don't allow any.
pip itself also validates the wheel archive (zip structure, metadata), which
is the content check (an HTML error page can't install).

Usage: python3 scripts/lock_requirements.py   (stdlib only; needs network)
"""
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "python-backend" / "requirements.txt"
OUT = ROOT / "python-backend" / "requirements.lock"
LINE = re.compile(r"^([A-Za-z0-9_.\-]+)==([A-Za-z0-9_.+\-]+)\s*(;.*)?$")


def digests(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as r:
        data = json.load(r)
    files = data.get("urls") or []
    if not files:
        sys.exit(f"FATAL: PyPI lists no files for {name}=={version}")
    yanked = [f["filename"] for f in files if f.get("yanked")]
    if yanked:
        print(f"WARNING: {name}=={version} has yanked files: {yanked}", file=sys.stderr)
    if not any(f["packagetype"] == "bdist_wheel" for f in files):
        sys.exit(f"FATAL: {name}=={version} has no wheels; --only-binary would fail")
    return sorted({f["digests"]["sha256"] for f in files})


def main() -> None:
    out = [
        "# GENERATED by scripts/lock_requirements.py from requirements.txt. Do not edit.",
        "# Hashes are PyPI's upload-time digests for every file of each pinned release.",
        "",
    ]
    for raw in SRC.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        m = LINE.match(line)
        if not m:
            sys.exit(f"FATAL: not an exact pin: {raw!r}")
        name, version, marker = m.group(1), m.group(2), (m.group(3) or "").strip()
        hashes = digests(name, version)
        req = f"{name}=={version}" + (f" {marker}" if marker else "")
        out.append(req + " \\")
        out.extend(f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "")
                   for i, h in enumerate(hashes))
        print(f"{name}=={version}: {len(hashes)} files")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
